"""
Builds ../js/data.js from the raw World Bank CSV files in data/raw/.

Run from the data/ folder:   python3 build_data.py

Sources (World Bank figures, via the open "datasets" collection on GitHub):
  raw/gdp_current_usd.csv   GDP in current US dollars      github.com/datasets/gdp
  raw/population.csv        Total population               github.com/datasets/population
  raw/country_codes.csv     ISO codes, names and regions   github.com/datasets/country-codes

The World Bank files also contain groups like "Euro area" or "High income".
Only real countries are kept (those with an ISO code and a UN region), plus
the World total, which is used for "share of world GDP".
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
RAW = HERE / "raw"
OUT = HERE.parent / "js" / "data.js"

FIRST_YEAR, LAST_YEAR = 1960, 2023

# Short names read better in a chart legend than official names.
NAME_FIXES = {
    "USA": "United States",
    "GBR": "United Kingdom",
    "BIH": "Bosnia and Herzegovina",
    "COD": "DR Congo",
    "COG": "Republic of the Congo",
    "XKX": "Kosovo",
}
EXTRA_REGIONS = {"XKX": "Europe"}  # Kosovo uses a World Bank code that is not in the ISO list


def load_countries() -> pd.DataFrame:
    codes = pd.read_csv(RAW / "country_codes.csv", keep_default_na=False)
    codes = codes.rename(columns={
        "ISO3166-1-Alpha-3": "code",
        "CLDR display name": "name",
        "Region Name": "region",
    })[["code", "name", "region"]]
    codes = codes[(codes["code"] != "") & (codes["region"] != "")]
    extra = pd.DataFrame([{"code": c, "name": "", "region": r} for c, r in EXTRA_REGIONS.items()])
    codes = pd.concat([codes, extra], ignore_index=True)
    codes["name"] = codes.apply(lambda row: NAME_FIXES.get(row["code"], row["name"]), axis=1)
    return codes.set_index("code")


def load_series(filename: str) -> pd.DataFrame:
    """Long CSV (code, year, value) -> wide table: one row per country, one column per year."""
    df = pd.read_csv(RAW / filename).rename(columns={"Country Code": "code", "Year": "year", "Value": "value"})
    df = df[(df["year"] >= FIRST_YEAR) & (df["year"] <= LAST_YEAR)]
    wide = df.pivot_table(index="code", columns="year", values="value", aggfunc="first")
    return wide.reindex(columns=range(FIRST_YEAR, LAST_YEAR + 1))


def to_list(row, scale=1.0, digits=0):
    """Numbers -> JSON-friendly list, with missing years as None (null in JS)."""
    out = []
    for v in row:
        if pd.isna(v):
            out.append(None)
        else:
            x = round(float(v) / scale, digits)
            out.append(int(x) if digits == 0 else x)
    return out


def main():
    countries = load_countries()
    gdp = load_series("gdp_current_usd.csv")
    pop = load_series("population.csv")

    records = []
    for code in sorted(set(gdp.index) & set(countries.index)):
        gdp_row = gdp.loc[code]
        if gdp_row.notna().sum() < 5:  # skip places with almost no data
            continue
        pop_row = pop.loc[code] if code in pop.index else pd.Series([None] * len(gdp_row))
        records.append({
            "code": code,
            "name": countries.loc[code, "name"],
            "region": countries.loc[code, "region"],
            "gdp": to_list(gdp_row, scale=1e6, digits=1),  # millions of US$
            "pop": to_list(pop_row),
        })

    world = to_list(gdp.loc["WLD"], scale=1e6, digits=1)

    data = {
        "firstYear": FIRST_YEAR,
        "lastYear": LAST_YEAR,
        "source": "World Bank, GDP (current US$) and population",
        "world": world,
        "countries": records,
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by data/build_data.py. Do not edit by hand.\n"
        f"window.GDP_DATA = {json.dumps(data, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(records)} countries, {FIRST_YEAR}-{LAST_YEAR}, to {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
